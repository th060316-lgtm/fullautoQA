# Reconstruct the preserved source substrate, then overlay the checked-out source.
[CmdletBinding()]
param(
  [Parameter(Mandatory=$true)][string]$RepositoryRoot,
  [Parameter(Mandatory=$true)][string]$Destination
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression.FileSystem
$RepositoryRoot = [IO.Path]::GetFullPath($RepositoryRoot)
$Destination = [IO.Path]::GetFullPath($Destination)
if (Test-Path -LiteralPath $Destination) { throw 'SOURCE_DESTINATION_MUST_BE_FRESH' }
$archive = Join-Path $RepositoryRoot '開発版/transfer/FullAutoQA_Recovery_Source_20261102.zip'
$zip = [IO.Compression.ZipFile]::OpenRead($archive)
try {
  foreach ($entry in $zip.Entries) {
    $name = $entry.FullName.Replace('\','/')
    if ($name.StartsWith('/') -or $name.Contains(':') -or @($name.Split('/')) -contains '..') { throw 'UNSAFE_SOURCE_ARCHIVE' }
    if ((($entry.ExternalAttributes -shr 16) -band 61440) -eq 40960) { throw 'SOURCE_ARCHIVE_SYMLINK' }
  }
} finally { $zip.Dispose() }
[IO.Compression.ZipFile]::ExtractToDirectory($archive, $Destination)
$matches = @(Get-ChildItem -LiteralPath $Destination -Recurse -Filter 'test_core.py' |
  Where-Object { $_.Directory.Name -eq 'TESTS' })
if ($matches.Count -ne 1) { throw ('SOURCE_ROOT_AMBIGUOUS:' + $matches.Count) }
$sourceRoot = $matches[0].Directory.Parent.FullName
$current = Join-Path $RepositoryRoot '開発版/source'
Get-ChildItem -LiteralPath $current -Force | ForEach-Object {
  Copy-Item -LiteralPath $_.FullName -Destination $sourceRoot -Recurse -Force
}
# Remove caches from the recovered substrate; never package host-generated bytecode.
Get-ChildItem -LiteralPath $sourceRoot -Directory -Recurse -Filter '__pycache__' |
  Remove-Item -Recurse -Force
Write-Output $sourceRoot
